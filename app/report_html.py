def save(report: dict[str, Any], output_dir: str | Path = "reports", locale: str = "ru") -> Path:
    path = report_path(report, output_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(report, locale=locale), encoding="utf-8")
    return path