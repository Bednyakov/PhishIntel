"""Compact Russian HTML renderer for JSON reports."""

from __future__ import annotations

import html
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .i18n import normalize_locale


def _text(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "да" if value else "нет"
    if isinstance(value, (dict, list)):
        return str(value)
    return str(value)


def _safe_name(target: str) -> str:
    value = re.sub(r"[^A-Za-z0-9._-]+", "_", target).strip("._")
    return value or "report"


def report_path(report: dict[str, Any], output_dir: str | Path = "reports") -> Path:
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H-%M-%SZ")
    return Path(output_dir) / f"{_safe_name(str(report.get('target', 'report')))}_{timestamp}.html"


def _row(label: str, value: Any) -> str:
    return f"<div class=\"row\"><span>{html.escape(label)}</span><strong>{html.escape(_text(value))}</strong></div>"


def _section_data(report: dict[str, Any], name: str) -> dict[str, Any]:
    """Return a domain section from both current and legacy report layouts."""
    value = report.get(name)
    if isinstance(value, dict):
        return value
    domain = report.get("domain")
    if isinstance(domain, dict) and isinstance(domain.get(name), dict):
        return domain[name]
    return {}


def _items(value: Any) -> list[Any]:
    if isinstance(value, list):
        return value
    if value in (None, "", {}, []):
        return []
    return [value]


def _value_list(value: Any) -> str:
    values = _items(value)
    return ", ".join(_text(item) for item in values) if values else "—"


